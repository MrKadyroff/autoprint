namespace AutoPrint.Services;

/// <summary>Понятная пользователю расшифровка причины сбоя печати + что сделать.</summary>
public record PrintErrorAdvice(string Title, string Message, IReadOnlyList<string> Steps);

/// <summary>
/// Превращает техническое сообщение об ошибке печати (спулер/сеть/таймаут) в понятную
/// формулировку для модалки: что случилось и что конкретно проверить/нажать.
/// </summary>
public static class PrintErrorClassifier
{
    public static PrintErrorAdvice Classify(string? errorMessage)
    {
        string m = (errorMessage ?? "").ToLowerInvariant();

        if (m.Contains("не подключён") || m.Contains("не подключен") || m.Contains("не сконфигурирован"))
            return new(
                "Принтер не подключён",
                "Не удалось напечатать чек — в приложении не выбран рабочий принтер.",
                new[]
                {
                    "Проверьте, что принтер включён (кнопка питания на корпусе).",
                    "Проверьте, что USB- или сетевой кабель подключён с обеих сторон.",
                    "Нажмите «Автонастройка в один клик» или «Определить и подключить»."
                });

        if (m.Contains("замят"))
            return new(
                "Замятие бумаги",
                "Принтер сообщил о замятии бумаги — печать остановлена.",
                new[]
                {
                    "Откройте крышку принтера и аккуратно уберите замятую бумагу.",
                    "Вставьте рулон заново и закройте крышку.",
                    "Задание автоматически повторится, либо нажмите «↻» рядом с ним."
                });

        if (m.Contains("нет бумаги") || m.Contains("бумаг"))
            return new(
                "Закончилась бумага",
                "В принтере закончилась чековая лента.",
                new[]
                {
                    "Вставьте новый рулон термобумаги.",
                    "Закройте крышку принтера до щелчка.",
                    "Задание напечатается автоматически после этого."
                });

        if (m.Contains("открыта крышка") || m.Contains("крышк"))
            return new(
                "Открыта крышка принтера",
                "Принтер сообщил, что крышка отсека с бумагой открыта.",
                new[]
                {
                    "Закройте крышку принтера до щелчка.",
                    "Убедитесь, что рулон бумаги установлен правильно."
                });

        if (m.Contains("оффлайн") || m.Contains("офлайн") || m.Contains("offline"))
            return new(
                "Принтер не отвечает (оффлайн)",
                "У вас не подключён принтер, либо он выключен.",
                new[]
                {
                    "Включите принтер кнопкой питания.",
                    "Проверьте провод (USB или сетевой) — не отошёл ли он.",
                    "Если принтер сетевой — проверьте, что он в той же сети (IP не сменился)."
                });

        if (m.Contains("состояние ошибки") || m.Contains("спулер не принял"))
            return new(
                "Принтер сообщает об ошибке",
                "Windows видит принтер, но он в состоянии ошибки и не берёт задание.",
                new[]
                {
                    "Проверьте индикаторы/дисплей на самом принтере.",
                    "Выключите принтер, подождите 5 секунд и включите снова.",
                    "Проверьте, что бумага заправлена и крышка закрыта."
                });

        if (m.Contains("не завершилась за") || m.Contains("timeout") || m.Contains("тайм"))
            return new(
                "Принтер завис / не отвечает",
                "Принтер не ответил вовремя — возможно, завис или потерял связь.",
                new[]
                {
                    "Выключите и включите принтер (кнопка питания).",
                    "Проверьте провод (USB или сетевой кабель).",
                    "Попробуйте напечатать ещё раз кнопкой «↻»."
                });

        if (m.Contains("недоступен") || m.Contains("отказано в подключении") || m.Contains("connection")
            || m.Contains("socket") || m.Contains("сети"))
            return new(
                "Нет связи с сетевым принтером",
                "Не удалось подключиться к принтеру по сети.",
                new[]
                {
                    "Проверьте, что принтер включён и подключён к сети (кабель на месте).",
                    "Проверьте, что IP-адрес принтера не изменился (распечатайте самотест).",
                    "Если Wi-Fi/DHCP — попробуйте переподключить принтер по сети или USB."
                });

        return new(
            "Не удалось напечатать чек",
            string.IsNullOrWhiteSpace(errorMessage) ? "Причина неизвестна." : errorMessage!,
            new[]
            {
                "Проверьте, что принтер включён и провод подключён.",
                "Проверьте бумагу и крышку принтера.",
                "Попробуйте повторить печать кнопкой «↻»."
            });
    }
}
